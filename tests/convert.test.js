import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {
  cleanPdfPages,
  convertToText,
  INVALID_PDF_ERROR,
  NO_PDF_TEXT_ERROR,
  NO_TEXT_ERROR,
  pdfToText,
} from '../server/materials/convert.js';

const fixture = (name) => fs.readFileSync(new URL(`./fixtures/${name}`, import.meta.url), 'utf8');
const binaryFixture = (name) => fs.readFileSync(new URL(`./fixtures/${name}`, import.meta.url));

test('SRT: removes sequence numbers and timestamps, keeps spoken text', () => {
  const text = convertToText(fixture('sample.srt'), 'srt');
  assert.equal(
    text,
    'Welcome to the lecture on photosynthesis. Plants turn light into chemical energy. 42 That is the answer.'
  );
  assert.doesNotMatch(text, /-->/);
});

test('VTT: removes header, notes, cue ids, timestamps and tags', () => {
  const text = convertToText(fixture('sample.vtt'), 'vtt');
  assert.equal(
    text,
    'Welcome to the lecture on photosynthesis. Plants turn light into chemical energy. ' +
      'Chlorophyll absorbs mostly red and blue light.'
  );
});

test('SRT with Windows line endings gives the same result', () => {
  const crlf = fixture('sample.srt').replace(/\r?\n/g, '\r\n');
  assert.equal(convertToText(crlf, 'srt'), convertToText(fixture('sample.srt'), 'srt'));
});

test('long subtitles are merged into paragraphs at sentence ends', () => {
  const sentence = 'This sentence is part of a long lecture about cells and energy.';
  const srt = Array.from(
    { length: 20 },
    (_, i) => `${i + 1}\n00:00:${String(i).padStart(2, '0')},000 --> 00:00:${String(i).padStart(2, '0')},900\n${sentence}\n`
  ).join('\n');
  const paragraphs = convertToText(srt, 'srt').split('\n\n');
  assert.ok(paragraphs.length > 1);
  for (const paragraph of paragraphs) assert.match(paragraph, /\.$/);
});

test('txt and text are returned unchanged', () => {
  const input = 'Line one.\n\n\nLine two.  ';
  assert.equal(convertToText(input, 'txt'), input);
  assert.equal(convertToText(input, 'text'), input);
});

test('empty result throws the exact error message', () => {
  assert.throws(() => convertToText('   \n\n', 'text'), { message: NO_TEXT_ERROR });
  assert.throws(() => convertToText('WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n', 'vtt'), {
    message: 'The file contains no readable text.',
  });
});

// The PDF fixtures are generated by tests/fixtures/make-pdf.js
test('PDF: text of both pages is extracted and cleaned', async () => {
  assert.equal(
    await pdfToText(binaryFixture('sample.pdf')),
    'Photosynthesis is the process by which green plants turn light into chemical energy. ' +
      'The process takes place in the chloroplasts of plant cells.\n\n' +
      'Chlorophyll absorbs mostly red and blue light and reflects green light.\n\n' +
      'Cellular respiration releases the energy stored in glucose. It takes place in the mitochondria.'
  );
});

test('PDF without a text layer is rejected with the exact message', async () => {
  await assert.rejects(pdfToText(binaryFixture('no-text.pdf')), { message: NO_PDF_TEXT_ERROR });
  assert.equal(
    NO_PDF_TEXT_ERROR,
    'This PDF contains no selectable text (scanned documents are not supported).'
  );
});

test('a file that is not a PDF is rejected', async () => {
  await assert.rejects(pdfToText(Buffer.from('%PDF-1.4 not really')), { message: INVALID_PDF_ERROR });
});

test('PDF cleanup: words hyphenated at line ends are joined', () => {
  assert.equal(
    cleanPdfPages([['The chloro-', 'plast and the Smith-', 'Jones method, see pages 3-', '5.']]),
    'The chloroplast and the Smith-Jones method, see pages 3- 5.'
  );
});

test('PDF cleanup: standalone page numbers at the top or bottom of a page are removed', () => {
  const pages = [
    ['1', 'First page text.'],
    ['Second page text.', 'Page 2'],
    ['- 3 -', 'Third page.', '42', 'More text.', '3 of 4'],
  ];
  // "42" stands alone in the middle of a page, so it is content and stays
  assert.equal(
    cleanPdfPages(pages),
    'First page text.\n\nSecond page text.\n\nThird page. 42 More text.'
  );
});

test('PDF cleanup: lines repeated on more than half of the pages are removed', () => {
  const pages = [
    ['Biology 101', 'Cells are small', 'Draft'],
    ['Biology 101', 'and divide.', 'Draft'],
    ['Biology 101', 'Summary', 'Energy comes from food.'],
    ['Summary', 'Plants use light.'],
  ];
  // "Biology 101" is on 3 of 4 pages; "Draft" and "Summary" are on exactly half, so they stay
  assert.equal(
    cleanPdfPages(pages),
    'Cells are small Draft and divide. Draft Summary Energy comes from food.\n\nSummary Plants use light.'
  );
  // A single page has no repeated headers

  assert.equal(cleanPdfPages([['Only page', 'Only page text.']]), 'Only page Only page text.');
});

test('PDF cleanup: lines are merged into paragraphs and whitespace is collapsed', () => {
  assert.equal(
    cleanPdfPages([['  First   line', 'continues here.', '', '', 'Second\tparagraph.  ']]),
    'First line continues here.\n\nSecond paragraph.'
  );
});
